const assert = require('node:assert/strict')
const { makeProvider } = require('./provider.cjs')
const { makeRunner } = require('./runner.cjs')
const { release } = require('./release.cjs')
const success = makeProvider()
release(success)
assert.deepEqual(success.calls, ['refresh', 'inspect', 'refresh', 'apply', 'refresh', 'verify', 'refresh', 'archive'])
const commandFailure = makeProvider({ failCommand: 'apply' })
assert.throws(() => release(commandFailure), /command failed/)
assert.deepEqual(commandFailure.calls, ['refresh', 'inspect', 'refresh', 'apply', 'refresh', 'archive'])
const refreshFailure = makeProvider({ failAt: 2 })
const run = makeRunner(refreshFailure)
assert.equal(run('inspect'), 'inspect')
assert.throws(() => run('apply'), /identity unavailable/)
assert.deepEqual(refreshFailure.calls, ['refresh', 'inspect', 'refresh'])
console.log('Every CLI invocation refreshes, including cleanup; refresh failure prevents invocation')
