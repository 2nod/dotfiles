const assert = require('node:assert/strict');
const { Sender } = require('./sender.cjs');
const { Transport } = require('./transport.cjs');
(async () => {
  const t = new Transport(); const s = new Sender(t);
  t.failure = 'after';
  assert.equal(await s.submit('hello'), false);
  assert.equal(s.draft, 'hello');
  assert.equal(await s.submit('hello'), true);
  assert.equal(t.events.length, 1, 'accepted delivery must not be sent again');
  assert.equal(t.calls, 1);
  assert.equal(s.draft, '');
  assert.equal(await s.submit('hello'), true);
  assert.equal(t.events.length, 2, 'a new identical message is a separate delivery');
  t.failure = 'after';
  assert.equal(await s.submit('world'), false);
  t.historyDown = true;
  assert.equal(await s.submit('world'), false);
  assert.equal(t.calls, 3, 'do not resend while acceptance cannot be checked');
  assert.equal(s.draft, 'world');
  t.historyDown = false;
  assert.equal(await s.submit('world'), true);
  assert.equal(t.events.length, 3);
  t.failure = 'before';
  assert.equal(await s.submit('again'), false);
  assert.equal(await s.submit('again'), true);
  assert.equal(t.events.length, 4, 'an unaccepted delivery remains retryable');
  console.log('lost response, history failure, intentional repeat, and unaccepted retry: passed');
})().catch(e => { console.error(e.message); process.exitCode = 1; });
